public class TypeCasting {
    public  static void main(String[] args){
        //narrowing conversdion
        int a=10;
        double b=a;
        System.out.println(b);
        
        //explicit type casting
        int y=15;
        int z=10;
        System.out.println("x/z"+((float)y/z));


    }
    
}
